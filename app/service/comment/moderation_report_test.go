func newCommentModerationReportRunner(t testing.TB) *commentModerationReportRunner {
	t.Helper()
	return &commentModerationReportRunner{
		service: &commentService{
			config: &appconfig.Config{
				CommentModerationConfig: newTestCommentModerationConfig(t),
			},
			logger: zap.NewNop(),
		},
		userEvents:      make(map[string][]time.Time),
		ipEvents:        make(map[string][]time.Time),
		duplicateEvents: make(map[string]int64),
	}
}

func (r *commentModerationReportRunner) run(ctx context.Context, commentID uint64,
	item commentModerationReportCase) commentModerationResult {
	input := commentModerationInput{
		CommentID: commentID,
		UserID:    item.UserID,
		ArticleID: item.ArticleID,
		ClientIP:  item.ClientIP,
		Content:   item.Content,
		Now:       item.Now,
	}
	result := r.service.moderateCommentWithBehavior(ctx, input,
		func(_ context.Context, input commentModerationInput, view commentModerationTextView,
			cfg appconfig.CommentModerationConfig) []commentModerationSignal {
			keys := buildCommentModerationBehaviorKeys(input.UserID, input.ArticleID, input.ClientIP, view.Normalized)
			state := commentModerationBehaviorState{
				UserCount:      int64(len(recentModerationReportEvents(r.userEvents[keys.user], input.Now, commentModerationSecondsToDuration(cfg.Behavior.UserWindowSeconds)))),
				IPCount:        int64(len(recentModerationReportEvents(r.ipEvents[keys.ip], input.Now, commentModerationSecondsToDuration(cfg.Behavior.IPWindowSeconds)))),
				DuplicateCount: r.duplicateEvents[keys.duplicate],
			}
			return []commentModerationSignal{commentModerationBehaviorSignal(state, cfg)}
		},
	)
	r.record(input)
	return result
}

func (r *commentModerationReportRunner) record(input commentModerationInput) {
	normalized := normalizeCommentModerationText(input.Content)
	keys := buildCommentModerationBehaviorKeys(input.UserID, input.ArticleID, input.ClientIP, normalized)
	r.userEvents[keys.user] = append(r.userEvents[keys.user], input.Now)
	r.ipEvents[keys.ip] = append(r.ipEvents[keys.ip], input.Now)
	r.duplicateEvents[keys.duplicate]++
}

func loadCommentModerationReportCases(t *testing.T, path string) []commentModerationReportCase {
	t.Helper()
	data, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("failed to read moderation report corpus %s: %v", path, err)
	}

	baseTime := time.Unix(1700000000, 0)
	cases := make([]commentModerationReportCase, 0, 300)
	categoryCounts := make(map[string]int)
	corpus := strings.TrimSuffix(string(data), "\n")
	corpus = strings.TrimSuffix(corpus, "\r")
	for _, line := range strings.Split(corpus, "\n") {
		line = strings.TrimRight(line, "\r")
		category := commentModerationReportCategoryByIndex(len(cases))
		categoryIndex := categoryCounts[category]
		categoryCounts[category]++
		item := newCommentModerationReportCase(
			baseTime,
			len(cases),
			categoryIndex,
			category,
			stripModerationReportCaseLabel(line),
		)
		item.RawContent = line
		cases = append(cases, item)
	}

	return cases
}

func loadCommentModerationReportCasesWithCategory(t *testing.T, path, category string) []commentModerationReportCase {
	t.Helper()
	data, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("failed to read moderation report corpus %s: %v", path, err)
	}

	baseTime := time.Unix(1700000000, 0)
	corpus := strings.TrimSuffix(string(data), "\n")
	corpus = strings.TrimSuffix(corpus, "\r")
	if strings.TrimSpace(corpus) == "" {
		return nil
	}
	lines := strings.Split(corpus, "\n")
	cases := make([]commentModerationReportCase, 0, len(lines))
	for _, line := range lines {
		line = strings.TrimRight(line, "\r")
		item := newCommentModerationReportCase(
			baseTime,
			len(cases),
			len(cases),
			category,
			stripModerationReportCaseLabel(line),
		)
		item.RawContent = line
		cases = append(cases, item)
	}
	return cases
}

func stripModerationReportCaseLabel(value string) string {
	index := strings.Index(value, "：")
	if index < 0 || !strings.Contains(value[:index], "样例") {
		return value
	}
	return value[index+len("："):]
}

