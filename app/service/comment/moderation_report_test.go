func writeCommentModerationReport(t *testing.T, cases []commentModerationReportCase, outputPath string) {
	t.Helper()
	runner := newCommentModerationReportRunner(t)
	statusCounts := make(map[string]int)
	reasonCounts := make(map[string]int)
	rows := make([]string, 0, len(cases))

	for index, item := range cases {
		result := runner.run(context.Background(), uint64(index+1), item)
		statusCounts[result.Status]++
		for _, reason := range result.Reasons {
			reasonCounts[reason]++
		}
		rows = append(rows, fmt.Sprintf(
			"%03d | status=%-8s | risk_score=%3d | final_score=%3d | deductions=%-120s | 原始评论=%s",
			index+1,
			result.Status,
			result.Score,
			moderationReportFinalScore(result.Score),
			formatModerationReportDeductions(result.Reasons),
			formatModerationReportContent(item.RawContent),
		))
	}

	reportLines := buildCommentModerationReportLines(cases, statusCounts, reasonCounts, rows)
	if err := os.WriteFile(outputPath, []byte(strings.Join(reportLines, "\n")+"\n"), 0644); err != nil {
		t.Fatalf("failed to write moderation report %s: %v", outputPath, err)
	}
}

